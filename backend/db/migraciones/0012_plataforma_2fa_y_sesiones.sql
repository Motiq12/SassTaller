-- B-06: la cuenta de plataforma (ve todos los talleres) entraba con la contraseña sola
-- y su token de 8 horas no se podía revocar.
--
-- 1. Segundo factor TOTP obligatorio, con las mismas columnas que el personal
--    (usuarios.totp_*). Una cuenta sin él configura la app en su próximo ingreso.
-- 2. Versión de credenciales (QA34-02): sube al cambiar o recuperar la contraseña y al
--    desactivar la cuenta. El login la lee junto con el hash y la deja en su sesión.
-- 3. Sesiones persistidas con su sid: cada pedido del panel comprueba que la sesión
--    siga abierta, que la cuenta siga activa y que la versión coincida.
--
-- Aditiva: columnas nuevas con valores por defecto y una tabla nueva. Las cuentas
-- existentes arrancan sin segundo factor y en la versión 0; los tokens viejos (sin sid)
-- dejan de valer y hay que volver a entrar, ya con el segundo factor.
ALTER TABLE plataforma_admins ADD COLUMN totp_secret varchar(64);
ALTER TABLE plataforma_admins ADD COLUMN totp_activado smallint NOT NULL DEFAULT 0;
ALTER TABLE plataforma_admins ADD COLUMN totp_backup text;
ALTER TABLE plataforma_admins ADD COLUMN totp_ultimo_contador bigint;
ALTER TABLE plataforma_admins ADD COLUMN credenciales_version integer NOT NULL DEFAULT 0;

CREATE TABLE plataforma_sesiones (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  admin_id integer NOT NULL,
  sid char(32) NOT NULL,
  agente varchar(255) DEFAULT NULL,
  ip varchar(64) DEFAULT NULL,
  creada timestamptz NOT NULL DEFAULT now(),
  ultima_vez timestamptz DEFAULT NULL,
  vence timestamptz NOT NULL,
  cerrada timestamptz DEFAULT NULL,
  credenciales_version integer NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  CONSTRAINT uq_plataforma_sesiones_sid UNIQUE (sid)
);
CREATE INDEX idx_plataforma_sesiones_admin ON plataforma_sesiones (admin_id);
-- Diferible como el resto de las FK del esquema: la restauración de un respaldo
-- carga las tablas en cualquier orden y valida al final.
ALTER TABLE plataforma_sesiones ADD CONSTRAINT plataforma_sesiones_admin_fk FOREIGN KEY (admin_id)
  REFERENCES plataforma_admins (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
