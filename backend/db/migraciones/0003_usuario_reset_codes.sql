-- Códigos para que el PERSONAL de un taller recupere su contraseña por correo.
--
-- Hasta ahora no había forma: el personal solo podía cambiarla con la sesión
-- iniciada, y quien la olvidaba tenía que escribirle a Motiq. Es la misma mecánica
-- que password_reset_codes (la de los clientes del portal): código de 6 dígitos con
-- hash bcrypt, 10 minutos, un solo uso y tope de intentos.
--
-- Va aparte de usuario_verify_codes a propósito: un código para confirmar el correo no
-- tiene por qué servir para cambiar la contraseña, ni al revés.
CREATE TABLE "usuario_reset_codes" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "tenant_id" integer NOT NULL,
  "usuario_id" integer NOT NULL,
  "code_hash" varchar(255) NOT NULL,
  "expires_at" timestamptz NOT NULL,
  "used" smallint NOT NULL DEFAULT 0,
  "attempts" integer NOT NULL DEFAULT 0,
  "created_at" timestamptz DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);
CREATE INDEX "idx_usuario_reset_codes_usuario" ON "usuario_reset_codes" ("tenant_id", "usuario_id", "used");
ALTER TABLE "usuario_reset_codes" ADD CONSTRAINT "fk_usuario_reset_codes_tenant"
  FOREIGN KEY ("tenant_id") REFERENCES "tenants" ("id") DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE "usuario_reset_codes" ADD CONSTRAINT "fk_usuario_reset_codes_usuario"
  FOREIGN KEY ("usuario_id") REFERENCES "usuarios" ("id") DEFERRABLE INITIALLY IMMEDIATE;
