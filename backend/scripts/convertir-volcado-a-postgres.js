#!/usr/bin/env node
// Convierte el volcado MySQL (db/sasstaller.sql) en dos archivos Postgres:
//
//   db/migraciones/0001_esquema_base.sql  — tablas, índices, claves foráneas, triggers
//   db/datos-prueba.sql                    — los dos talleres de prueba del volcado
//
// Es una herramienta de UNA vez: la migración de MySQL a Postgres se hizo con esto y
// desde entonces el esquema evoluciona con migraciones nuevas en db/migraciones/. Se
// conserva para que quede claro de dónde salió el esquema base y para poder repetirlo
// si hiciera falta (p. ej. si el volcado se corrige antes de cerrar la migración).
//
// Decisiones de tipos (las que cambian comportamiento están marcadas con ⚠):
//   int AUTO_INCREMENT  → integer GENERATED BY DEFAULT AS IDENTITY
//                         (BY DEFAULT para que los datos de prueba puedan traer su id)
//   tinyint / (1)       → smallint. NO boolean: el código compara `activo = 1` y
//                         `=== 1` en cientos de lugares; con smallint siguen valiendo.
//   enum(...)           → varchar + CHECK con los mismos valores
//   timestamp/datetime  → timestamptz (todo en UTC, igual que el volcado)
//   json                → jsonb
//   year                → smallint
//   ⚠ columnas *email*  → citext. MySQL compara texto sin distinguir mayúsculas
//                         (collation _ci) y Postgres sí: sin esto `Lu@x.com` dejaría de
//                         encontrar a `lu@x.com` y se romperían logins sin ningún error.
//   ON UPDATE CURRENT_TIMESTAMP → trigger BEFORE UPDATE que pisa updated_at
//   FOREIGN KEY         → al final, DEFERRABLE INITIALLY IMMEDIATE: para la app es lo
//                         mismo que antes; permite cargar datos de prueba sin ordenar.
//
// Uso: node scripts/convertir-volcado-a-postgres.js [ruta-del-volcado]
const fs = require('fs');
const path = require('path');
const { SIN_PASSWORD } = require('../db/credenciales');

const RAIZ = path.join(__dirname, '..');
const ORIGEN = process.argv[2] || path.join(RAIZ, 'db/sasstaller.sql');
const DESTINO_ESQUEMA = path.join(RAIZ, 'db/migraciones/0001_esquema_base.sql');
const DESTINO_DATOS = path.join(RAIZ, 'db/datos-prueba.sql');

const volcado = fs.readFileSync(ORIGEN, 'utf8').replace(/\r\n/g, '\n');

// ── Parseo de CREATE TABLE ────────────────────────────────────────────────
const tablas = [];   // { nombre, columnas: [], pk, uniques, indices, fks, comentarios }
for (const m of volcado.matchAll(/CREATE TABLE `(\w+)` \(\n([\s\S]*?)\n\) ENGINE=[^;]*;/g)) {
  const t = { nombre: m[1], columnas: [], pk: null, uniques: [], indices: [], fks: [] };
  for (let linea of m[2].split('\n')) {
    linea = linea.trim().replace(/,$/, '');
    let x;
    if ((x = linea.match(/^PRIMARY KEY \((.+)\)$/))) t.pk = cols(x[1]);
    else if ((x = linea.match(/^UNIQUE KEY `(\w+)` \((.+)\)$/))) t.uniques.push({ nombre: x[1], columnas: cols(x[2]) });
    else if ((x = linea.match(/^KEY `(\w+)` \((.+)\)$/))) t.indices.push({ nombre: x[1], columnas: cols(x[2]) });
    else if ((x = linea.match(/^CONSTRAINT `(\w+)` FOREIGN KEY \((.+?)\) REFERENCES `(\w+)` \((.+?)\)(.*)$/))) {
      t.fks.push({ nombre: x[1], columnas: cols(x[2]), ref: x[3], refColumnas: cols(x[4]), extra: x[5].trim() });
    } else if ((x = linea.match(/^`(\w+)` (.+)$/))) t.columnas.push(columna(x[1], x[2]));
    else if (linea) throw new Error(`Línea no reconocida en ${t.nombre}: ${linea}`);
  }
  tablas.push(t);
}

// `a`,`b`(100) → ['a','b'] (los prefijos de índice de MySQL no existen en Postgres)
function cols(s) {
  return s.split(',').map(c => c.trim().replace(/^`(\w+)`(\(\d+\))?.*$/, '$1'));
}

function columna(nombre, resto) {
  const c = { nombre, notNull: /\bNOT NULL\b/.test(resto), identidad: /\bAUTO_INCREMENT\b/.test(resto),
    alActualizar: /ON UPDATE CURRENT_TIMESTAMP/.test(resto), defecto: null, comentario: null, generada: null };
  const tipoCrudo = resto.match(/^(\w+(?:\([^)]*\))?)/)[1];
  c.tipo = tipoPg(nombre, tipoCrudo);
  if (/^enum/i.test(tipoCrudo)) c.check = tipoCrudo.match(/\((.*)\)/)[1];
  // citext no tiene largo: se conserva el tope que daba el varchar de MySQL.
  if (c.tipo === 'citext') c.largoMax = Number(tipoCrudo.match(/\((\d+)\)/)[1]);

  const def = resto.match(/\bDEFAULT ('(?:[^'\\]|\\.)*'|CURRENT_TIMESTAMP|NULL|-?[\d.]+)/);
  if (def && def[1] !== 'NULL') c.defecto = defectoPg(def[1], c.tipo);

  const com = resto.match(/\bCOMMENT '((?:[^'\\]|\\.)*)'/);
  if (com) c.comentario = com[1].replace(/\\'/g, "'");

  const gen = resto.match(/GENERATED ALWAYS AS \((.+)\) STORED/);
  if (gen) {
    c.generada = gen[1].replace(/_utf8mb4'/g, "'").replace(/`(\w+)`/g, '$1');
    c.defecto = null;
  }
  return c;
}

function tipoPg(nombre, t) {
  const base = t.toLowerCase().replace(/\(.*/, '');
  const args = (t.match(/\((.*)\)/) || [])[1];
  switch (base) {
    case 'int': return 'integer';
    case 'bigint': return 'bigint';
    case 'tinyint': case 'smallint': case 'year': return 'smallint';
    case 'varchar': return /email/i.test(nombre) ? 'citext' : `varchar(${args})`;
    case 'char': return `char(${args})`;
    case 'text': case 'mediumtext': case 'longtext': return 'text';
    case 'enum': {
      const largo = Math.max(...args.split(',').map(v => v.trim().length - 2));
      return `varchar(${Math.max(largo, 1)})`;
    }
    case 'decimal': return `numeric(${args})`;
    case 'double': return 'double precision';
    case 'json': return 'jsonb';
    case 'date': return 'date';
    case 'time': return 'time';
    case 'timestamp': case 'datetime': return 'timestamptz';
    default: throw new Error(`Tipo sin mapear: ${t} (${nombre})`);
  }
}

function defectoPg(v, tipo) {
  if (v === 'CURRENT_TIMESTAMP') return 'CURRENT_TIMESTAMP';
  if (/^'.*'$/.test(v)) {
    const crudo = v.slice(1, -1);
    // '1', '0.00': en MySQL los numéricos vienen entre comillas; en Postgres van sin ellas.
    if (/^(smallint|integer|bigint|numeric|double)/.test(tipo) && /^-?[\d.]+$/.test(crudo)) return crudo;
    return `'${crudo.replace(/\\'/g, "''")}'`;
  }
  return v;
}

// ── Nombres de índice ─────────────────────────────────────────────────────
// En MySQL el nombre de un índice es por tabla; en Postgres es global al esquema
// (`cliente_id` aparece en cuatro tablas). Los genéricos se prefijan con la tabla.
const usos = {};
for (const t of tablas) for (const i of [...t.indices, ...t.uniques]) usos[i.nombre] = (usos[i.nombre] || 0) + 1;
const columnasDe = (t) => new Set(t.columnas.map(c => c.nombre));
function nombreIndice(t, i) {
  const n = (usos[i.nombre] > 1 || columnasDe(t).has(i.nombre) || !/^(idx|uq)_/.test(i.nombre))
    ? `idx_${t.nombre}_${i.nombre}` : i.nombre;
  return n.slice(0, 63);
}

// ── Esquema ───────────────────────────────────────────────────────────────
const q = (id) => `"${id}"`;
const sal = [];
sal.push(`-- Esquema base de Motiq en Postgres.
-- Generado por scripts/convertir-volcado-a-postgres.js a partir del volcado MySQL
-- (db/sasstaller.sql). Desde acá el esquema evoluciona con migraciones nuevas en esta
-- misma carpeta (0002_..., 0003_...); este archivo no se edita a mano.

CREATE EXTENSION IF NOT EXISTS citext;

-- Reemplazo de ON UPDATE CURRENT_TIMESTAMP de MySQL.
CREATE OR REPLACE FUNCTION motiq_tocar_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
`);

for (const t of tablas) {
  const defs = t.columnas.map(c => {
    let d = `  ${q(c.nombre)} ${c.tipo}`;
    if (c.generada) return `${d} GENERATED ALWAYS AS (${c.generada}) STORED`;
    if (c.identidad) d += ' GENERATED BY DEFAULT AS IDENTITY';
    if (c.notNull && !c.identidad) d += ' NOT NULL';
    if (c.defecto != null) d += ` DEFAULT ${c.defecto}`;
    if (c.check) d += ` CHECK (${q(c.nombre)} IN (${c.check}))`;
    if (c.largoMax) d += ` CHECK (char_length(${q(c.nombre)}) <= ${c.largoMax})`;
    return d;
  });
  if (t.pk) defs.push(`  PRIMARY KEY (${t.pk.map(q).join(', ')})`);
  for (const u of t.uniques) defs.push(`  CONSTRAINT ${q(nombreIndice(t, u))} UNIQUE (${u.columnas.map(q).join(', ')})`);
  sal.push(`CREATE TABLE ${q(t.nombre)} (\n${defs.join(',\n')}\n);`);

  for (const i of t.indices) {
    sal.push(`CREATE INDEX ${q(nombreIndice(t, i))} ON ${q(t.nombre)} (${i.columnas.map(q).join(', ')});`);
  }
  for (const c of t.columnas.filter(c => c.comentario)) {
    sal.push(`COMMENT ON COLUMN ${q(t.nombre)}.${q(c.nombre)} IS '${c.comentario.replace(/'/g, "''")}';`);
  }
  for (const c of t.columnas.filter(c => c.alActualizar)) {
    if (c.nombre !== 'updated_at') throw new Error(`ON UPDATE en columna inesperada: ${t.nombre}.${c.nombre}`);
    sal.push(`CREATE TRIGGER ${q(`trg_${t.nombre}_updated_at`)} BEFORE UPDATE ON ${q(t.nombre)}\n  FOR EACH ROW EXECUTE FUNCTION motiq_tocar_updated_at();`);
  }
  sal.push('');
}

sal.push('-- Claves foráneas al final: así el orden de creación de las tablas no importa.');
for (const t of tablas) {
  for (const f of t.fks) {
    sal.push(`ALTER TABLE ${q(t.nombre)} ADD CONSTRAINT ${q(f.nombre)} FOREIGN KEY (${f.columnas.map(q).join(', ')})` +
      ` REFERENCES ${q(f.ref)} (${f.refColumnas.map(q).join(', ')})${f.extra ? ' ' + f.extra : ''} DEFERRABLE INITIALLY IMMEDIATE;`);
  }
}

// ── Datos ─────────────────────────────────────────────────────────────────
// Lee un literal de MySQL (con escapes de barra) y lo reescribe en sintaxis Postgres.
function valores(cuerpo) {
  const filas = [];
  let i = 0;
  const n = cuerpo.length;
  while (i < n) {
    if (cuerpo[i] !== '(') { i++; continue; }
    i++;
    const fila = [];
    let actual = '';
    while (i < n && cuerpo[i] !== ')') {
      const ch = cuerpo[i];
      if (ch === "'") {
        i++;
        let s = '';
        while (i < n && cuerpo[i] !== "'") {
          if (cuerpo[i] === '\\') {
            const e = cuerpo[++i];
            s += { n: '\n', r: '\r', t: '\t', '0': '\0', Z: '\x1a' }[e] ?? e;
          } else s += cuerpo[i];
          i++;
        }
        i++;
        actual = { texto: s };
      } else if (ch === ',') { fila.push(actual); actual = ''; i++; }
      else { actual += ch; i++; }
    }
    fila.push(actual);
    filas.push(fila);
    i++;
  }
  return filas;
}
const literal = (v) => (typeof v === 'object' ? `'${v.texto.replace(/\0/g, '').replace(/'/g, "''")}'` : (v.trim() === 'NULL' ? 'NULL' : v.trim()));

const datos = [`-- Datos de prueba: los dos talleres del volcado MySQL original.
-- Generado por scripts/convertir-volcado-a-postgres.js. Se carga sobre una base recién
-- migrada (npm run db:importar). Las fechas del volcado están en UTC.

SET TIME ZONE 'UTC';
BEGIN;
SET CONSTRAINTS ALL DEFERRED;
`];
const generadas = Object.fromEntries(tablas.map(t => [t.nombre, new Set(t.columnas.filter(c => c.generada).map(c => c.nombre))]));
// Códigos de un solo uso (verificación, login, recuperación): en el volcado son restos
// vencidos de pruebas viejas. No sirven para nada y son hashes de 6 dígitos, que se
// revierten por fuerza bruta en segundos: no viajan.
const SIN_DATOS = new Set(['email_verify_codes', 'login_codes', 'password_reset_codes', 'usuario_verify_codes']);
for (const m of volcado.matchAll(/^INSERT INTO `(\w+)` \(([^)]*)\) VALUES (.*);$/gm)) {
  const tabla = m[1];
  if (SIN_DATOS.has(tabla)) continue;
  const columnas = cols(m[2]);
  const quitar = columnas.map((c, k) => (generadas[tabla].has(c) ? k : -1)).filter(k => k >= 0);
  const usar = columnas.filter((_, k) => !quitar.includes(k));
  // Ninguna contraseña que funcione sale de acá (ver db/credenciales.js): el volcado
  // MySQL traía los hashes de cuentas semilla cuyas claves están escritas en el README.
  // Las del personal las genera `npm run db:importar`; las de clientes quedan sin
  // contraseña (entran por código al correo).
  const iHash = ['usuarios', 'clientes'].includes(tabla) ? usar.indexOf('password_hash') : -1;
  const filas = valores(m[3]).map(f => f.filter((_, k) => !quitar.includes(k)))
    .map(f => (iHash >= 0 && typeof f[iHash] === 'object' ? f.map((v, k) => (k === iHash ? { texto: SIN_PASSWORD } : v)) : f));
  filas.forEach(f => { if (f.length !== usar.length) throw new Error(`Fila con ${f.length} valores en ${tabla} (esperaba ${usar.length})`); });
  datos.push(`INSERT INTO ${q(tabla)} (${usar.map(q).join(', ')}) VALUES\n` +
    filas.map(f => `  (${f.map(literal).join(', ')})`).join(',\n') + ';');
}
datos.push('\n-- Las identidades siguen después del último id cargado.');
for (const t of tablas) {
  const id = t.columnas.find(c => c.identidad);
  if (id) {
    datos.push(`SELECT setval(pg_get_serial_sequence('${t.nombre}', '${id.nombre}'), ` +
      `COALESCE((SELECT MAX(${q(id.nombre)}) FROM ${q(t.nombre)}), 1), ` +
      `(SELECT MAX(${q(id.nombre)}) FROM ${q(t.nombre)}) IS NOT NULL);`);
  }
}
datos.push('COMMIT;');

fs.mkdirSync(path.dirname(DESTINO_ESQUEMA), { recursive: true });
fs.writeFileSync(DESTINO_ESQUEMA, sal.join('\n') + '\n');
fs.writeFileSync(DESTINO_DATOS, datos.join('\n') + '\n');
console.log(`${tablas.length} tablas → ${path.relative(RAIZ, DESTINO_ESQUEMA)}`);
console.log(`${datos.filter(d => d.startsWith('INSERT')).length} tablas con datos → ${path.relative(RAIZ, DESTINO_DATOS)}`);
